// Regenerates src/cdk/stateful-generated.ts from the AWS service spec that
// @aws-cdk/cloudformation-diff already depends on. Run: npm run gen:stateful
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { loadAwsServiceSpecSync } = require('@aws-cdk/aws-service-spec');
const specVersion = require('@aws-cdk/aws-service-spec/package.json').version;

const db = loadAwsServiceSpecSync();
const types = db
  .all('resource')
  .filter((r) => r.isStateful)
  .map((r) => r.cloudFormationType)
  .sort();

const body = `// Generated by scripts/gen-cfn-stateful.mjs from @aws-cdk/aws-service-spec ${specVersion}. Do not edit.
export const SPEC_STATEFUL_TYPES: readonly string[] = [
${types.map((t) => `  '${t}',`).join('\n')}
];
`;
writeFileSync(new URL('../src/cdk/stateful-generated.ts', import.meta.url), body);
console.log(`${types.length} stateful types written`);
